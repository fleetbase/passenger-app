/**
 * Points the app at the build's brand files.
 *
 * A client build keeps everything it owns in `brand/` (which this repository never
 * ships), so pulling a new release never touches a client file:
 *
 *   brand/passenger.brand.ts       branding (name, colours, type, appearance, contacts)
 *   brand/passenger.extensions.ts  screen and component overrides, custom routes
 *   brand/fonts/*.ttf|otf          font files named by their PostScript name
 *   brand/logo.png                 the logo (optional)
 *   brand/logo-dark.png            the logo for dark mode (optional)
 *
 * Each one is optional. Missing files fall back to the templates at the repository
 * root (passenger.brand.ts, passenger.extensions.ts) or to nothing.
 *
 * It also writes PASSENGER_HOST, PASSENGER_KEY and PASSENGER_SAMPLE_DATA from the
 * environment or .env.
 *
 * The result is written to src/generated (git-ignored) as plain modules, so Metro,
 * webpack, Jest and tsc all resolve it the same way. It runs from babel.config.js,
 * metro.config.js, webpack.config.js, postinstall and typecheck, and only rewrites a
 * file whose content changed so watchers don't loop.
 */
const fs = require('fs');
const path = require('path');

const FONT_EXTENSIONS = ['.ttf', '.otf'];
const HEADER = '// Generated by scripts/link-brand.js from brand/ (or the root templates). Do not edit.\n';

function writeIfChanged(file, content) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === content) {
        return;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
}

const firstExisting = (root, candidates) => candidates.find((candidate) => ['.ts', '.tsx', '.js'].some((ext) => fs.existsSync(path.join(root, candidate + ext))));

function linkBrand(root = path.resolve(__dirname, '..')) {
    const brandDir = path.join(root, 'brand');
    const outDir = path.join(root, 'src', 'generated');
    const rel = (target) => path.relative(outDir, path.join(root, target)).split(path.sep).join('/');

    const brandConfig = firstExisting(root, ['brand/passenger.brand', 'passenger.brand']);
    const brandExtensions = firstExisting(root, ['brand/passenger.extensions', 'passenger.extensions']);

    writeIfChanged(path.join(outDir, 'brand-config.ts'), `${HEADER}import brandConfig from '${rel(brandConfig)}';\n\nexport default brandConfig;\n`);
    writeIfChanged(path.join(outDir, 'brand-extensions.ts'), `${HEADER}import brandExtensions from '${rel(brandExtensions)}';\n\nexport default brandExtensions;\n`);

    const fontsDir = path.join(brandDir, 'fonts');
    const fonts = fs.existsSync(fontsDir)
        ? fs
              .readdirSync(fontsDir)
              .filter((file) => FONT_EXTENSIONS.includes(path.extname(file).toLowerCase()))
              .sort()
        : [];
    const fontEntries = fonts.map((file) => {
        const name = path.basename(file, path.extname(file));
        return `    ${JSON.stringify(name)}: require('${rel(`brand/fonts/${file}`)}'),`;
    });

    const logo = fs.existsSync(path.join(brandDir, 'logo.png')) ? 'brand/logo.png' : null;
    const logoDark = fs.existsSync(path.join(brandDir, 'logo-dark.png')) ? 'brand/logo-dark.png' : null;

    // Native builds link brand/fonts (react-native.config.js) and never read the font
    // files through this map; only the web build loads them from here.
    writeIfChanged(
        path.join(outDir, 'brand-assets.web.ts'),
        `${HEADER}export const brandFontFiles: Record<string, string> = {\n${fontEntries.join('\n')}${fontEntries.length ? '\n' : ''}};\n\n` +
            `export const logo: any = ${logo ? `require('${rel(logo)}')` : 'null'};\nexport const logoDark: any = ${logoDark ? `require('${rel(logoDark)}')` : 'null'};\n`
    );
    writeIfChanged(
        path.join(outDir, 'brand-assets.ts'),
        `${HEADER}export const brandFontFiles: Record<string, string> = {};\n\n` +
            `export const logo: any = ${logo ? `require('${rel(logo)}')` : 'null'};\nexport const logoDark: any = ${logoDark ? `require('${rel(logoDark)}')` : 'null'};\n`
    );

    // Connection settings: the environment wins over .env, so a build pipeline can set them.
    const envFile = path.join(root, '.env');
    const fileEnv = fs.existsSync(envFile)
        ? Object.fromEntries(
              fs
                  .readFileSync(envFile, 'utf8')
                  .split('\n')
                  .map((line) => line.trim())
                  .filter((line) => line && !line.startsWith('#') && line.includes('='))
                  .map((line) => [line.slice(0, line.indexOf('=')).trim(), line.slice(line.indexOf('=') + 1).trim()])
          )
        : {};
    const setting = (name) => process.env[name] ?? fileEnv[name] ?? '';
    const host = setting('PASSENGER_HOST');
    writeIfChanged(
        path.join(outDir, 'env.ts'),
        `${HEADER}export const env = ${JSON.stringify(
            { host, key: setting('PASSENGER_KEY'), sampleData: setting('PASSENGER_SAMPLE_DATA') === 'true' },
            null,
            4
        )};\n`
    );

    return { brandConfig, brandExtensions, host, fonts: fonts.length, logo: Boolean(logo) };
}

module.exports = { linkBrand };

if (require.main === module) {
    const result = linkBrand();
    console.log(`[link-brand] branding: ${result.brandConfig}, extensions: ${result.brandExtensions}, fonts: ${result.fonts}, logo: ${result.logo ? 'yes' : 'no'}`);
}
